function normalizarCodigo(codigo) {
  return String(codigo || '').trim().replace(/\s+/g, ' ').toUpperCase();
}

const INDICE_PARTNER = new Map(
  LISTA_PRECIOS_PARTNER_2026.map((item) => [normalizarCodigo(item.codigo), item])
);

export function buscarProductoPartner(codigo) {
  return INDICE_PARTNER.get(normalizarCodigo(codigo)) || null;
}

export function obtenerPrecioPartner(codigo) {
  const producto = buscarProductoPartner(codigo);
  return producto ? Number(producto.precioPartner) : null;
}
